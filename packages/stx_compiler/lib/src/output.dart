import 'dart:io';

import 'package:dart_style/dart_style.dart';
import 'package:path/path.dart' as p;

const generatedHeader = '// Auto-generated by stratastax:codegen. Do not edit manually.';

/// One generated Dart file; [path] is relative to the output directory and uses `/`.
final class GeneratedFile {
  const GeneratedFile(this.path, this.content);

  final String path;
  final String content;
}

/// Formats generated sources with dart_style. Formatting also parses the file, so a renderer bug
/// that produces invalid syntax fails here, not in the consumer's build.
final class GeneratedFormatter {
  GeneratedFormatter({int pageWidth = 120})
    : _formatter = DartFormatter(languageVersion: DartFormatter.latestLanguageVersion, pageWidth: pageWidth);

  final DartFormatter _formatter;

  GeneratedFile format(GeneratedFile file) => GeneratedFile(file.path, _formatter.format(file.content, uri: file.path));
}

final class WriteResult {
  const WriteResult({required this.written, required this.unchanged, required this.deleted});

  final List<String> written;
  final int unchanged;
  final List<String> deleted;
}

/// Writes generated files into [outputDir]. A file is only written when its content changes (so
/// hot reload and file watchers stay quiet); generated files under [ownedDirs] that are no longer
/// produced are deleted.
WriteResult writeGenerated(String outputDir, List<GeneratedFile> files, {required List<String> ownedDirs}) {
  final written = <String>[];
  var unchanged = 0;
  final expected = <String>{};

  for (final file in files) {
    final target = File(p.joinAll([outputDir, ...file.path.split('/')]));
    expected.add(p.normalize(target.absolute.path));
    if (target.existsSync() && target.readAsStringSync() == file.content) {
      unchanged++;
      continue;
    }
    target.parent.createSync(recursive: true);
    target.writeAsStringSync(file.content);
    written.add(file.path);
  }

  final deleted = <String>[];
  for (final owned in ownedDirs) {
    final dir = Directory(p.join(outputDir, owned));
    if (!dir.existsSync()) continue;
    for (final entity in dir.listSync(recursive: true).whereType<File>()) {
      final path = p.normalize(entity.absolute.path);
      if (path.endsWith('.g.dart') && !expected.contains(path)) {
        entity.deleteSync();
        deleted.add(p.relative(path, from: outputDir));
      }
    }
    _deleteEmptyDirs(dir);
  }
  return WriteResult(written: written, unchanged: unchanged, deleted: deleted);
}

void _deleteEmptyDirs(Directory dir) {
  for (final child in dir.listSync().whereType<Directory>()) {
    _deleteEmptyDirs(child);
  }
  if (dir.listSync().isEmpty) dir.deleteSync();
}
